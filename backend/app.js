const express = require('express');
const cors = require('cors');
const helmet = require('helmet');
const session = require('express-session');
const MongoStore = require('connect-mongo');
const cookieParser = require('cookie-parser');
const mongoose = require('mongoose');
const path = require('node:path');
const fs = require('node:fs');
const { rateLimit } = require('express-rate-limit');
const { getJwtSecret } = require('./config/jwtConfig');
const { authenticate, requireRole } = require('./middleware/auth');
const { errorHandler, notFound } = require('./middleware/errorHandler');
const { requestObservation } = require('./middleware/requestObservation');
const { createHealthChecks } = require('./services/platformHealth');
function createApp(options = {}) {
  const app = express();
  const secret = getJwtSecret();
  const allowedOrigins = new Set([process.env.CLIENT_URL || 'http://localhost:5173', 'http://127.0.0.1:5173']);
  app.disable('x-powered-by');
  app.use(requestObservation({ write: options.requestLogWriter || (process.env.NODE_ENV === 'test' ? () => {} : undefined) }));
  app.use(helmet({ contentSecurityPolicy: process.env.NODE_ENV === 'production' ? undefined : false }));
  app.use(cors({ origin(origin, callback) { callback(null, !origin || allowedOrigins.has(origin)); }, credentials: true, exposedHeaders: ['X-Request-ID'] }));
  const health = createHealthChecks();
  app.get('/api/live', health.live);
  app.get('/api/health', health.ready);
  app.use(express.json({ limit: '1mb' }));
  app.use(cookieParser(secret));
  app.use(rateLimit({ windowMs: 15 * 60 * 1000, max: 500, standardHeaders: true, legacyHeaders: false }));
  const store = options.sessionStore || MongoStore.create({ client: mongoose.connection.getClient(), collectionName: 'oauth_sessions' });
  app.locals.sessionStore = store;
  app.use(session({ name: 'ttwar_oauth', secret, store, resave: false, saveUninitialized: false, cookie: { httpOnly: true, sameSite: 'lax', secure: process.env.NODE_ENV === 'production', maxAge: 10 * 60 * 1000 } }));
  const passport = require('./modules/auth/config/passport');
  app.use(passport.initialize());
  app.use('/api/auth', require('./modules/auth/routes/auth')());
  app.use('/api/auth', require('./modules/auth/routes/oauth'));
  app.use('/api/auth', require('./routes/auth'));
  app.use('/api/user', require('./modules/auth/routes/user'));
  for (const [url, file] of Object.entries({ jobs: 'jobs', companies: 'companies', messages: 'messages', cv: 'cv', applications: 'applications', 'saved-jobs': 'savedJobs', admin: 'admin', problems: 'problemRoutes', 'study-plans': 'studyPlans' })) app.use('/api/' + url, require('./routes/' + file));
  app.use('/api/ai', require('./routes/ai')());
  app.use('/api/submissions', require('./routes/submissionRoutes')());
  app.use('/api/management', authenticate, requireRole('admin'), require('./routes/management'));
  app.use('/api/company', require('./routes/companies'));
  const swaggerUi = require('swagger-ui-express');
  app.use('/api/docs', swaggerUi.serve, swaggerUi.setup(require('./swagger/config')));
  app.use('/api', notFound);
  const dist = path.resolve(__dirname, '../frontend/dist');
  if (fs.existsSync(dist)) { app.use(express.static(dist)); app.get('*', (_req, res) => res.sendFile(path.join(dist, 'index.html'))); }
  app.use(notFound);
  app.use(errorHandler);
  return app;
}
module.exports = { createApp };
